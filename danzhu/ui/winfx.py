    tex = Texture.create(size=(d, d), colorfmt="rgba")
    tex.blit_buffer(bytes(job["buf"]), colorfmt="rgba", bufferfmt="ubyte")
    tex.mag_filter = "linear"
    tex.min_filter = "linear"
    _CUP_BALL_TEX[bet] = tex
    del _BAKE_JOB[bet]
    return tex


