def _clamp_accum(a):
    """把固定步长累加器的积压截到单帧上限。

    ⚠️ 必须截: 不截则"帧慢 → 补更多物理步 → 更慢"自我放大(真机实测单帧跑过 37 步)。
       代价是那一帧丢掉时间(球走得比墙钟慢一点), 这是刻意取舍;
       反过来"把积压留到下帧再还"是错的, 会让之后每帧都跑满上限。
    """
    _lim = MAX_STEPS_PER_FRAME * FIXED_DT
    return _lim if a > _lim else a


